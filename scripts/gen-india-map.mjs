#!/usr/bin/env node
/**
 * gen-india-map.mjs — builds src/components/sections/indiaMapData.ts
 *
 * Sources (both cached in scripts/.cache/, gitignored):
 *   - Natural Earth 1:10m Admin 0 Countries, "India point-of-view" edition (public domain):
 *     the neighbouring countries and India's outline as depicted by the Government of India
 *     (full Jammu & Kashmir and Ladakh).
 *   - DataMeet India states (CC-BY 4.0): internal state / UT borders, same depiction.
 *
 * Projection: equirectangular with a cos(22 deg) x-scale, which keeps India's proportions natural.
 * Output: SVG path strings in one coordinate space. Rings are simplified (Douglas-Peucker).
 *
 * Usage: node scripts/gen-india-map.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const NE = join(ROOT, 'scripts', '.cache', 'ne_10m_admin_0_countries_ind.geojson');
const ST = join(ROOT, 'scripts', '.cache', 'india-states.geojson');
const OUT = join(ROOT, 'src', 'components', 'sections', 'indiaMapData.ts');

const LON0 = 40, LON1 = 122, LAT0 = 0, LAT1 = 42;
const K = 10;                       // svg units per degree of latitude
const CX = Math.cos((22 * Math.PI) / 180);
const W = Math.round((LON1 - LON0) * CX * K), H = (LAT1 - LAT0) * K;
const px = (lon, lat) => [(lon - LON0) * CX * K, (LAT1 - lat) * K];

function dp(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, L = Math.hypot(dx, dy) || 1e-9;
    let m = 0, mi = -1;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / L;
      if (d > m) { m = d; mi = i; }
    }
    if (m > tol && mi > 0) { keep[mi] = 1; stack.push([a, mi], [mi, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const inFrame = (ring) => ring.some(([lo, la]) => lo > LON0 - 2 && lo < LON1 + 2 && la > LAT0 - 2 && la < LAT1 + 2);
const num = (n) => (Math.round(n * 10) / 10).toString();

function ringPath(ring, tol) {
  /* a closed ring has identical ends, so split it at the point farthest from the start first */
  const all = ring.map(([lo, la]) => px(lo, la));
  let fi = 0, fd = -1;
  all.forEach((p, i) => { const d = Math.hypot(p[0] - all[0][0], p[1] - all[0][1]); if (d > fd) { fd = d; fi = i; } });
  const a = dp(all.slice(0, fi + 1), tol), b = dp(all.slice(fi), tol);
  const pts = a.concat(b.slice(1));
  if (pts.length < 4) return '';
  return 'M' + pts.map(([x, y]) => `${num(x)} ${num(y)}`).join('L') + 'Z';
}
function geomPath(g, tol, minArea = 0) {
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  let d = '';
  for (const poly of polys) {
    if (!inFrame(poly[0])) continue;
    if (minArea) {
      const xs = poly[0].map((p) => p[0]), ys = poly[0].map((p) => p[1]);
      if ((Math.max(...xs) - Math.min(...xs)) * (Math.max(...ys) - Math.min(...ys)) < minArea) continue;
    }
    for (const ring of poly) d += ringPath(ring, tol);
  }
  return d;
}

const ne = JSON.parse(readFileSync(NE, 'utf8'));
const st = JSON.parse(readFileSync(ST, 'utf8'));

let land = '', indiaBase = '';
for (const f of ne.features) {
  const p = f.properties;
  const iso = p.ISO_A3 || p.ADM0_A3 || p.SOV_A3;
  if (iso === 'IND' || p.NAME === 'India') indiaBase = geomPath(f.geometry, 0.45);
  else land += geomPath(f.geometry, 1.2, 0.05);
}

const states = st.features.map((f) => ({
  n: f.properties.ST_NM,
  d: geomPath(f.geometry, 0.5),
})).filter((s) => s.d);

const ts = `/* AUTO-GENERATED by scripts/gen-india-map.mjs, do not edit.
 * Natural Earth 1:10m (India point-of-view, public domain) + DataMeet India states (CC-BY 4.0).
 * Boundaries follow the Government of India depiction. */

export const MAP_W = ${W};
export const MAP_H = ${H};
export const MAP_LON0 = ${LON0};
export const MAP_LAT1 = ${LAT1};
export const MAP_K = ${K};
export const MAP_CX = ${CX.toFixed(5)};

/** lon/lat -> svg user units */
export const mapProject = (lon: number, lat: number) => ({
  x: (lon - MAP_LON0) * MAP_CX * MAP_K,
  y: (MAP_LAT1 - lat) * MAP_K,
});

export const LAND_PATH = ${JSON.stringify(land)};
export const INDIA_BASE_PATH = ${JSON.stringify(indiaBase)};
export const INDIA_STATES: { n: string; d: string }[] = ${JSON.stringify(states)};
`;
writeFileSync(OUT, ts);
console.log('written', OUT, (ts.length / 1024).toFixed(0) + ' KB', 'states:', states.length, 'size', W, H);
