/**
 * Regenerates the admin product catalogue snapshot from src/content/products.ts, so it can never
 * drift from the real catalogue. Runs after `next build` (postbuild) and from scripts/dev-sync.sh:
 * writes out/admin/lib/catalogue.php and refreshes the committed copy in public/admin/lib/.
 *
 * Each row is [slug, name, published, details]. Columns 0-2 are the original 3-column shape;
 * `details` carries the build-time values the product editor shows as "Default: ...".
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { loadContent } from './lib/content.mjs';

const ROOT = join(import.meta.dirname, '..');
const { products, productGroups, MATERIAL_LABELS, MACHINE_LABELS, productPath, productPhoto } = await loadContent();

const q = s => "'" + String(s).split("\\").join("\\\\").split("'").join("\\'") + "'";
const lit = v => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') return String(v);
  if (Array.isArray(v)) return '[' + v.map(lit).join(', ') + ']';
  if (typeof v === 'object') return '[' + Object.entries(v).map(([k, x]) => `${q(k)} => ${lit(x)}`).join(', ') + ']';
  return q(v);
};

const rows = products.map(p => {
  const g = p.group ? productGroups.find(x => x.id === p.group) : null;
  // Admin preview image: the product photo (/images/products/<slug>.webp), but only once the file exists in public/
  // (photos are generated later; a missing file would show a broken image in the panel). Old catalogue crops are not used.
  const photo = productPhoto(p);
  const img = photo && existsSync(join(ROOT, 'public', photo)) ? { src: photo, alt: `${p.name}, Alok Plastics` } : null;
  const details = {
    group: g ? { id: g.id, name: g.name, slug: g.slug } : null,
    path: g ? productPath(p) : null,
    material: p.material ? (MATERIAL_LABELS[p.material] ?? p.material) : '',
    sku: p.sku ?? '',
    hsn: p.hsn ?? '',
    moq: p.moq ?? '',
    packing: p.packing ?? '',
    summary: p.summary ?? '',
    machines: Array.isArray(p.machine) ? p.machine.map(m => MACHINE_LABELS[m] ?? m) : [],
    variants: (p.variants ?? []).map(v => ({ label: v.label, note: v.note ?? '' })),
    image: img ? { src: img.src, alt: img.alt ?? '' } : null,
  };
  // Commerce fields: emitted only when the build-time Product defines them (today none do, so the admin
  // shows "Not set, customers see Price on request"). Saved edits in data/products.json always win.
  if (typeof p.price === 'number') details.price = p.price;
  if (typeof p.stock === 'number') details.stock = p.stock;
  if (p.availability) details.availability = p.availability;
  if (Array.isArray(p.keywords) && p.keywords.length) details.keywords = p.keywords.map(String);
  if (p.brand) details.brand = String(p.brand);
  if (p.featured) details.featured = true;
  if (p.status && p.status !== 'active') details.status = p.status;
  return `    [${q(p.slug)}, ${q(p.name)}, ${p.published ? 'true' : 'false'}, ${lit(details)}],`;
}).join('\n');

const php = `<?php
/**
 * GENERATED by scripts/generate-catalogue.mjs from src/content/products.ts (runs in postbuild).
 * Do not edit by hand. Row: [slug, name, published, details]; details = group{id,name,slug}|null, path,
 * material, sku, hsn, moq, packing, summary, machines[], variants[{label,note}], image{src,alt}|null, and (only when set at build time)
 * price, stock, availability, keywords[], brand, featured, status.
 */
return [
${rows}
];
`;
const groupsPhp = `<?php
/**
 * GENERATED by scripts/generate-catalogue.mjs from src/content/products.ts (runs in postbuild).
 * Do not edit by hand. The website's product groups, used by the admin product editor.
 */
return [
${productGroups.map(g => `    ['id' => ${q(g.id)}, 'name' => ${q(g.name)}, 'slug' => ${q(g.slug)}],`).join('\n')}
];
`;
for (const rel of ['public/admin/lib/catalogue.php', 'out/admin/lib/catalogue.php']) {
  const file = join(ROOT, rel);
  if (!existsSync(dirname(file))) { mkdirSync(dirname(file), { recursive: true }); }
  writeFileSync(file, php);
  writeFileSync(join(dirname(file), 'groups.php'), groupsPhp);
}
console.log(`catalogue.php: ${products.length} products, groups.php: ${productGroups.length} groups`);
